"""Writing the suite out.

Generated code is read far more often than generated code is run, and this
particular generated code arrives in somebody's repository uninvited. So every
file explains itself: which metrics it holds, what each one catches, why it was
chosen for this target, and what a failure would mean. The explanation is not a
courtesy -- a suite whose reasoning is invisible gets deleted the first time it
disagrees with its owner, and it will disagree.

Three things are deliberately *not* generated.

**The metric implementations.** Faithfulness, answer relevancy and the rest are
already correct in DeepEval, and reimplementing them would be a worse version of
somebody else's solved problem. The emitted files call it.

**The application entry point.** `harness.py` imports the function the scanner
found and adapts it. Guessing an interface tends to produce a suite that runs
against nothing and reports a confident zero, so where the shape is unclear the
harness raises with a message naming the file and line to fix.

**Any answer a human owes.** See `goldens`.
"""

