def _wrap(text: str, width: int = 76, indent: str = "",
          hang: str | None = None) -> str:
    """Fill, with continuation lines indented under the first.

    `hang` defaults to `indent`; a deeper one gives a hanging indent, so a
    wrapped bullet stays visibly part of its bullet rather than colliding with
    the left margin and reading as a new item.
    """
    return textwrap.fill(" ".join(text.split()), width,
                         initial_indent=indent,
                         subsequent_indent=indent if hang is None else hang)


def _why_block(pipeline: Pipeline) -> str:
    """The docstring that tells the reader why this file exists."""
    lines = [f"{pipeline.target.title()} evals: {pipeline.risk.value}.", ""]
    lines.append(_wrap(
        {"component": "This checks one piece in isolation. Passing here does "
                      "not mean the pipeline works -- see the workflow evals.",
         "workflow": "This checks the composition. Components that each pass "
                     "on their own still compose into a broken pipeline: the "
                     "classic case is a retriever that returns the right "
                     "document at rank five while the generator answers from "
                     "rank one. Neither component misbehaved.",
         "application": "This checks the whole thing end to end, including the "
                        "properties that make a correct system undeployable.",
         }[pipeline.level.value]))
    lines += ["", "Why these metrics:", ""]
    for metric in pipeline.metrics:
        lines.append(_wrap(f"{metric.name} -- {metric.catches}",
                           indent="  ", hang="      "))
        detail = []
        if metric.reference is Reference.BASED:
            detail.append("needs a reference answer, so it starts blocked")
        if metric.mechanism is Mechanism.JUDGEMENT:
            detail.append("scored holistically, so it uses G-Eval rather than a "
                          "bare judge: a one-line criterion gets re-interpreted "
                          "on every call and an integer score flips between "
                          "adjacent digits")
        if metric.triangulates:
            detail.append("read it beside " + ", ".join(metric.triangulates))
        if not metric.higher_is_better:
            detail.append("lower is better")
        for item in detail:
            lines.append(_wrap(f"({item})", indent="      ", hang="       "))
        lines.append("")
    if pipeline.rationale:
        lines.append("Why this target was classified the way it was:")
        lines += [_wrap(f"- {r}", indent="  ", hang="    ")
                  for r in pipeline.rationale]
    return "\n".join(lines).rstrip()


def _metric_expr(metric: Metric, judge: str) -> str:
    """The DeepEval construction for one metric."""
    if metric.mechanism is Mechanism.JUDGEMENT and metric.method is Method.MODEL_GRADED:
        criterion = (metric.geval_criterion or metric.catches).replace('"', "'")
        params = ["LLMTestCaseParams.INPUT", "LLMTestCaseParams.ACTUAL_OUTPUT"]
        if metric.reference is Reference.BASED:
            params.append("LLMTestCaseParams.EXPECTED_OUTPUT")
        return (
            f'GEval(\n'
            f'        name="{metric.name}",\n'
            f'        criteria=(\n{_quoted(criterion, 12)}\n        ),\n'
            f'        evaluation_params=[{", ".join(params)}],\n'
            f'        model=JUDGE,\n'
            f'        threshold=THRESHOLDS["{metric.key}"],\n'
            f'    )')

    builtin = {
        "faithfulness": "FaithfulnessMetric",
        "answer_relevancy": "AnswerRelevancyMetric",
        "contextual_relevance": "ContextualRelevancyMetric",
        "contextual_recall": "ContextualRecallMetric",
        "contextual_precision": "ContextualPrecisionMetric",
        "toxicity": "ToxicityMetric",
        "pii_leakage": "PIILeakageMetric",
    }.get(metric.name)
    if builtin:
        return (f'{builtin}(threshold=THRESHOLDS["{metric.key}"], '
                f'model=JUDGE, include_reason=True)')
    # Programmatic metrics have no DeepEval equivalent; the harness measures them.
    return f'local_metric("{metric.key}")'


def _quoted(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join(f'{pad}"{line} "' for line in textwrap.wrap(text, 66))


def _eval_file(pipeline: Pipeline, judge: str) -> str:
    needs_geval = any(m.mechanism is Mechanism.JUDGEMENT and
                      m.method is Method.MODEL_GRADED for m in pipeline.metrics)
    builtins = sorted({
        {"faithfulness": "FaithfulnessMetric",
         "answer_relevancy": "AnswerRelevancyMetric",
         "contextual_relevance": "ContextualRelevancyMetric",
         "contextual_recall": "ContextualRecallMetric",
         "contextual_precision": "ContextualPrecisionMetric",
         "toxicity": "ToxicityMetric",
         "pii_leakage": "PIILeakageMetric"}[m.name]
        for m in pipeline.metrics
        if m.name in {"faithfulness", "answer_relevancy", "contextual_relevance",
                      "contextual_recall", "contextual_precision", "toxicity",
                      "pii_leakage"}})

    imports = [BANNER, '"""', _why_block(pipeline), '"""', "",
               "from livingeval_evals.harness import (",
               "    JUDGE, THRESHOLDS, load_cases, local_metric, run_pipeline,",
               ")", ""]
    if builtins:
        imports.append("from deepeval.metrics import " + ", ".join(builtins))
    if needs_geval:
        imports += ["from deepeval.metrics import GEval",
                    "from deepeval.test_case import LLMTestCaseParams"]
    imports.append("")

    # (registry key, metric). Paired rather than listed, for two reasons a live
    # run made obvious: DeepEval labels results with its own display name
    # ("PII Leakage", "toxicity [GEval]"), which never matches a registry key
    # and leaves the gate with nothing to compare; and each metric has to be
    # scored against its own dataset, or injection probes get judged for
    # toxicity and the number means nothing.
    metric_lines = ",\n    ".join(
        f'("{m.key}", {_metric_expr(m, judge)})' for m in pipeline.metrics)
    body = f'''
NAME = "{pipeline.slug}"

# (registry key, metric). Paired rather than listed, for two reasons the live
# run made obvious: DeepEval labels results with its own display name
# ("PII Leakage", "toxicity [GEval]"), which never matches a registry key and
# leaves the gate with nothing to compare; and each metric must be scored
# against its own dataset, or injection probes get judged for toxicity and the
# score means nothing.
METRICS = [
    {metric_lines},
]

# Golden sets, keyed by the metric that consumes them. Sets marked incomplete in
# their JSON are skipped with a warning rather than scored against empty answers.
CASES = load_cases({[m.key for m in pipeline.metrics]!r})


def run() -> dict:
    """Score this pipeline. See `harness.run_pipeline` for the shape."""
    return run_pipeline(NAME, METRICS, CASES)


if __name__ == "__main__":
    import json
    print(json.dumps(run(), indent=2))
'''
    return "\n".join(imports) + body


