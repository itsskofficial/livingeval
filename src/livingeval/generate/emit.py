def _explanation(plan: Plan, goldens: dict[str, GoldenSet]) -> str:
    lines = [
        "# Why this suite looks like this", "",
        plan.summary(), "",
        "Generated by `livingeval init`. Every choice below is explained, because "
        "you should be able to disagree with any of them.", "",
        "## What was found", "",
        "| file | line | function | classified as | confidence |",
        "|---|---|---|---|---|",
    ]
    for site in plan.sites:
        lines.append(f"| `{site.path}` | {site.line} | `{site.function}()` | "
                     f"{site.archetype} | {site.confidence:.0%} |")
    lines += ["", "The classification decides which metrics apply, so it is worth "
                  "checking. Reasons given:", ""]
    for site in plan.sites:
        lines.append(f"- **`{site.function}()`** — " + "; ".join(site.rationale))

    lines += ["", "## The pipelines", ""]
    for pipeline in plan.pipelines:
        lines += [f"### `{pipeline.slug}`", "",
                  f"*{pipeline.level.value} level, {pipeline.risk.value} risk.*", "",
                  "| metric | catches | needs |", "|---|---|---|"]
        for metric in pipeline.metrics:
            if metric.reference is Reference.BASED:
                needs = "a reference answer from you"
            elif metric.key in NEEDS_INSTRUMENTATION:
                needs = _brief(NEEDS_INSTRUMENTATION[metric.key])
            else:
                needs = "nothing — runs now"
            lines.append(f"| `{metric.name}` | {metric.catches} | {needs} |")
        lines.append("")

    lines += ["## The datasets", ""]
    for key, golden in sorted(goldens.items()):
        state = "complete" if golden.complete else "**awaiting your answers**"
        lines += [f"### `{key}` — {state}", "", golden.why, ""]

    lines += [
        "## What livingeval adds once this is running", "",
        "The suite above tells you whether your scores changed. Three questions it "
        "cannot answer on its own, and which `livingeval gate` does:", "",
        "- **Is the change real?** A paired test with a p-value, rather than "
        "comparing against a hand-picked noise threshold.",
        "- **Could this suite have caught the regression?** Detection power, "
        "simulated against a named regression and reported with its false-alarm rate.",
        "- **Does the suite still represent your traffic?** Coverage — the share of "
        "today's traffic sitting near something the suite contains.", "",
        "That last one is why the gate is three-valued. `PASS`, `FAIL`, and `BLIND`: "
        "\"no regression detected, and this suite could not have detected one\" is a "
        "different claim from \"no regression\".",
    ]
    return "\n".join(lines) + "\n"


def emit(plan: Plan, goldens: dict[str, GoldenSet], root: Path,
         judge: str = "openai:gpt-4o-mini", scope: str = "",
         protect: set[str] | None = None) -> Emission:
    """Write the whole suite under `root/livingeval_evals`.

    A package rather than a loose directory, because `run_suite` imports the
    eval modules by name and a plain folder makes that depend on the working
    directory.

    `protect` names files the caller has determined a human edited since they
    were written. They are skipped and reported. Golden sets are always merged
    rather than replaced, whether or not they are protected -- see
    `sync.write_goldens_preserving` for why that one is not negotiable.
    """
    package = root / "livingeval_evals"
    package.mkdir(parents=True, exist_ok=True)
    protect = protect or set()
    written: list[Path] = []
    skipped: list[str] = []
    records: list[FileRecord] = []

    def put(name: str, text: str, kind: str = "eval") -> None:
        if name in protect:
            skipped.append(name)
            return
        path = package / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
        records.append(FileRecord(path=name, written=digest(text), kind=kind))

    put("__init__.py", f'{BANNER}\n"""Generated eval suite. See WHY.md."""\n')
    put("harness.py", _harness(plan, judge))

    for pipeline in plan.pipelines:
        put(f"{pipeline.slug}.py", _eval_file(pipeline, judge))

    registry = {
        m.key: {"direction": "higher" if m.higher_is_better else "lower",
                "noise": m.noise_hint,
                # False until `livingeval baseline` measures the real spread.
                # The gate returns BLIND rather than PASS while this is False,
                # because comparing against a guess is not evidence of stability.
                "measured": False,
                "risk": m.risk.value,
                "catches": m.catches}
        for p in plan.pipelines for m in p.metrics
    }
    put("metric_registry.py", REGISTRY.format(
        banner=BANNER, registry=_pretty(registry)), "registry")
    put("run_suite.py", RUNNER.format(
        banner=BANNER, pipelines=[p.slug for p in plan.pipelines]), "eval")
    put("WHY.md", _explanation(plan, goldens), "doc")

    # Golden sets go through the merge path unconditionally. A dataset somebody
    # spent an afternoon labelling must survive every regeneration, and making
    # that depend on a flag is how it eventually does not.
    preserved = write_goldens_preserving(package, goldens)
    golden_paths = sorted((package / "goldens").glob("*.json"))

    Manifest(
        generated_at=time.time(), judge=judge, scope=scope,
        sites=[SiteRecord(ident=s.ident, path=str(s.path), function=s.function,
                          provider=s.provider, archetype=s.archetype,
                          fingerprint=site_digest(s), line=s.line)
               for s in plan.sites],
        files=records,
        goldens={k: {"complete": g.complete, "cases": len(g.cases)}
                 for k, g in goldens.items()},
        metrics=sorted({m.key for p in plan.pipelines for m in p.metrics}),
    ).save(package)

    return Emission(
        files=written, goldens=golden_paths,
        runnable=plan.runnable_count, blocked=plan.blocked_count,
        preserved=preserved, skipped=skipped)


def _pretty(mapping: dict) -> str:
    import json
    return json.dumps(mapping, indent=4).replace(": true", ": True").replace(
        ": false", ": False").replace(": null", ": None")
